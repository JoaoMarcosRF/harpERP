class I18n:
    """Global language manager supporting live switching between 'en' and 'pt-br'."""

    _current_lang = "en"
    _listeners = []

    @classmethod
    def get_lang(cls):
        return cls._current_lang

    @classmethod
    def is_en(cls):
        return cls._current_lang == "en"

    @classmethod
    def set_lang(cls, lang):
        cls._current_lang = "pt-br" if str(lang).lower() == "pt-br" else "en"
        for cb in list(cls._listeners):
            try:
                cb()
            except Exception:
                pass
        return cls._current_lang

    @classmethod
    def toggle(cls):
        new_lang = "pt-br" if cls._current_lang == "en" else "en"
        return cls.set_lang(new_lang)

    @classmethod
    def register_listener(cls, callback):
        if callback not in cls._listeners:
            cls._listeners.append(callback)

    @classmethod
    def t(cls, key, **kwargs):
        table = TRANSLATIONS.get(cls._current_lang, TRANSLATIONS["en"])
        text = table.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text


def t(key, **kwargs):
    """Shorthand translation helper."""
    return I18n.t(key, **kwargs)

